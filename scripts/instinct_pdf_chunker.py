def _looks_like_non_pdf_or_corrupt_pdf(exc: Exception) -> bool:
    message = f"{type(exc).__name__}: {exc}".lower()
    return any(
        needle in message
        for needle in (
            "invalid pdf",
            "ole header",
            "pdfstreamerror",
            "pdf read error",
            "eof marker",
            "malformed",
            "not a valid pdf",
            "cannot read an empty file",
        )
    )


