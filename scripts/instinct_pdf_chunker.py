def load_term_index(
    dictionary_csv: Path | None = None,
    *,
    term_types: set[str] | frozenset[str] = DEFAULT_TERM_TYPES,
) -> list[DictionaryTerm]:
    if dictionary_csv is None:
        return built_in_term_index()
    try:
        rows = _aws_data_api_query(
            """
SELECT canonical_name, aliases, term_type, category, confidence_score
FROM rag_dictionary_term
WHERE active = 1
ORDER BY priority_score DESC, canonical_name;
""".strip()
        )
        alias_rows = _aws_data_api_query(
            """
SELECT t.term_type, t.canonical_name, a.alias_text
FROM rag_dictionary_term_alias a
JOIN rag_dictionary_term t ON t.id = a.dictionary_term_id
WHERE t.active = 1
ORDER BY t.priority_score DESC, t.canonical_name, a.alias_text;
""".strip()
        )

        alias_map: dict[tuple[str, str], list[str]] = {}
        for row in alias_rows:
            key = (str(row.get("term_type") or "").strip(), str(row.get("canonical_name") or "").strip())
            alias_map.setdefault(key, [])
            alias_text = str(row.get("alias_text") or "").strip()
            if alias_text and alias_text not in alias_map[key]:
                alias_map[key].append(alias_text)

        terms: list[DictionaryTerm] = []
        for row in rows:
            term_type = str(row.get("term_type") or "").strip().lower()
            canonical_name = str(row.get("canonical_name") or "").strip()
            if term_type not in term_types or not canonical_name:
                continue
            if not _parse_bool(str(row.get("active", "1"))):
                continue
            try:
                confidence = float(row.get("confidence_score") or 1.0)
            except ValueError:
                confidence = 1.0
            aliases = list(dict.fromkeys([canonical_name]))
            raw_aliases = row.get("aliases")
            if isinstance(raw_aliases, str):
                aliases.extend(_split_aliases(raw_aliases))
            aliases.extend(alias_map.get((term_type, canonical_name), []))
            terms.append(
                DictionaryTerm(
                    term_type=term_type,
                    canonical_name=canonical_name,
                    aliases=tuple(dict.fromkeys(alias.strip() for alias in aliases if alias.strip())),
                    category=str(row.get("category") or "").strip() or None,
                    confidence=confidence,
                )
            )
        if terms:
            return terms
    except Exception:
        pass

    path = dictionary_csv or find_default_dictionary_csv()
    if path is None:
        return built_in_term_index()

    terms: list[DictionaryTerm] = []
    with path.open(newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        for row in reader:
            term_type = str(row.get("term_type") or "").strip().lower()
            canonical_name = str(row.get("canonical_name") or "").strip()
            if term_type not in term_types or not canonical_name or not _parse_bool(row.get("active")):
                continue
            try:
                confidence = float(row.get("confidence") or row.get("confidence_score") or 1.0)
            except ValueError:
                confidence = 1.0
            aliases = tuple(dict.fromkeys((canonical_name, *_split_aliases(row.get("aliases")))))
            terms.append(
                DictionaryTerm(
                    term_type=term_type,
                    canonical_name=canonical_name,
                    aliases=aliases,
                    category=str(row.get("category") or "").strip() or None,
                    confidence=confidence,
                )
            )
    return terms or built_in_term_index()


def detect_terms_in_text(text: str, terms: Iterable[DictionaryTerm], *, page_number: int) -> list[DetectedTerm]:
    detected: dict[tuple[str, str, str], DetectedTerm] = {}
    lowered_text = text.lower()
    for term in terms:
        for alias in term.aliases:
            alias = str(alias).strip()
            if len(alias) < 3:
                continue
            alias = alias.encode("utf-8", "ignore").decode("utf-8", "ignore")
            if len(alias) < 3:
                continue
            alias_lower = alias.lower()
            count = lowered_text.count(alias_lower)
            if not count:
                continue
            matched_text = alias
            key = (term.term_type, term.canonical_name, alias_lower)
            detected[key] = DetectedTerm(
                term_type=term.term_type,
                canonical_name=term.canonical_name,
                matched_text=matched_text,
                page_number=page_number,
                count=count,
                confidence=term.confidence,
            )
    return sorted(detected.values(), key=lambda item: (item.term_type, item.canonical_name, item.matched_text))


def detected_terms_to_metadata(terms: Iterable[DetectedTerm]) -> list[dict[str, Any]]:
    return [
        {
            "term_type": term.term_type,
            "canonical_name": term.canonical_name,
            "matched_text": term.matched_text,
            "page_number": term.page_number,
            "count": term.count,
            "confidence": term.confidence,
        }
        for term in terms
    ]


def summarize_detected_terms(terms: Iterable[DetectedTerm]) -> dict[str, list[str]]:
    grouped: dict[str, list[str]] = {"medication": [], "treatment": [], "product": []}
    for term in terms:
        grouped.setdefault(term.term_type, [])
        if term.canonical_name not in grouped[term.term_type]:
            grouped[term.term_type].append(term.canonical_name)
    return {key: sorted(values) for key, values in grouped.items() if values}


def _normalize_table_text(text: str) -> str:
    lines = [re.sub(r"\s+", " ", line).strip() for line in text.splitlines()]
    return "\n".join(line for line in lines if line)


def _is_date_token(token: str) -> bool:
    return bool(re.fullmatch(r"\d{1,2}/\d{1,2}/\d{2,4}", token))


def _extract_table_records(
    pages: list[str],
    term_summary: dict[str, list[str]],
    *,
    family: str | None = None,
) -> list[dict[str, str]]:
    records: list[dict[str, str]] = []
    known_terms = [term for values in term_summary.values() for term in values]
    for page_text in pages:
        raw_lines = [line.rstrip() for line in page_text.splitlines() if line.strip()]
        if not raw_lines:
            continue
        normalized_lines = [re.sub(r"\s+", " ", line).strip() for line in raw_lines]
        if not any(normalized_lines):
            continue

        if family == "transaction_history":
            header_seen = False
            row_lines: list[str] = []
            for line in normalized_lines:
                if not line:
                    continue
                lower = line.lower()
                if "date provider patient product" in lower or "date provider" in lower and "amount" in lower:
                    header_seen = True
                    continue
                if not header_seen:
                    continue
                if re.match(r"^\d{1,2}/\d{1,2}/\d{2,4}\b", line):
                    if row_lines:
                        records.append(_parse_transaction_history_row(" ".join(row_lines), known_terms))
                    row_lines = [line]
                elif row_lines:
                    row_lines.append(line)
            if row_lines:
                records.append(_parse_transaction_history_row(" ".join(row_lines), known_terms))
            continue

        if family == "antech_lab":
            current_block: list[str] = []
            for line in normalized_lines:
                lower = line.lower()
                if "date:" in lower and current_block and any("code name" in part.lower() for part in current_block):
                    records.append(_parse_lab_history_block(current_block, known_terms))
                    current_block = [line]
                    continue
                if "lab test history" in lower or "name result unit indicator" in lower or "reference low" in lower:
                    current_block.append(line)
                    continue
                if current_block:
                    current_block.append(line)
            if current_block:
                records.append(_parse_lab_history_block(current_block, known_terms))
            continue

        blocks: list[list[str]] = []
        current_block: list[str] = []
        for raw_line in normalized_lines:
            if not raw_line:
                continue
            if "codename" in raw_line.lower() and "provider" in raw_line.lower():
                continue
            if re.match(r"^(RK|KA|BORAO)\b", raw_line):
                if current_block:
                    blocks.append(current_block)
                current_block = [raw_line]
                continue
            if current_block:
                current_block.append(raw_line)
        if current_block:
            blocks.append(current_block)

        for block in blocks:
            raw_line = " ".join(block)
            if not re.match(r"^(RK|KA|BORAO)\b", raw_line):
                continue
            code = raw_line.split()[0]
            dates = re.findall(r"\b\d{1,2}/\d{1,2}/\d{2,4}\b", raw_line)
            provider = "Christine B. Cassidy, DVM" if "Christine B." in raw_line and "Cassidy" in raw_line and "DVM" in raw_line else ""
            row_terms = [term for term in known_terms if term.lower() in raw_line.lower()]
            description = ""
            if "Imrab 1" in raw_line:
                description = "Imrab 1 Rabies Canine 1yr"
            elif "DA2P" in raw_line:
                description = "DA2P + Leptospirosis 4 Annual" if "Leptospirosis" in raw_line else "DA2P Annual"
            elif "Bordetella" in raw_line:
                description = "Bordetella Oral Vaccine"
            records.append(
                {
                    "code": code,
                    "dates": ", ".join(dates),
                    "provider": provider,
                    "description": description,
                    "terms": ", ".join(row_terms),
                    "raw": raw_line,
                }
            )
    return records


def _parse_transaction_history_row(row_text: str, known_terms: list[str]) -> dict[str, str]:
    text = re.sub(r"\s+", " ", row_text).strip()
    dates = re.findall(r"\b\d{1,2}/\d{1,2}/\d{2,4}\b", text)
    provider = ""
    provider_match = re.search(r"\b([A-Z][a-z]+(?: [A-Z]\.)?(?: [A-Z][a-z]+)?(?:, DVM)?)\b", text)
    if provider_match and "date" not in provider_match.group(1).lower():
        provider = provider_match.group(1)
    product = ""
    if " physical exam" in text.lower():
        product = "Physical Exam"
    elif " vaccine" in text.lower():
        product = "Vaccine"
    elif " labs" in text.lower() or "lab" in text.lower():
        product = "Lab"
    row_terms = [term for term in known_terms if term.lower() in text.lower()]
    return {
        "code": dates[0] if dates else "",
        "dates": ", ".join(dates),
        "provider": provider,
        "description": product,
        "terms": ", ".join(row_terms),
        "raw": text,
    }


def _parse_lab_history_block(block_lines: list[str], known_terms: list[str]) -> dict[str, str]:
    text = _normalize_table_text("\n".join(block_lines))
    lines = [line for line in text.splitlines() if line.strip()]
    header = next((line for line in lines if "name" in line.lower() and "result" in line.lower()), "")
    code = ""
    description = ""
    provider = ""
    dates = re.findall(r"\b\d{1,2}/\d{1,2}/\d{2,4}\b", text)
    for line in lines:
        if line.lower().startswith("code name:"):
            code = line.split(":", 1)[1].strip().split()[0] if ":" in line else ""
        elif line.lower().startswith("description:"):
            description = line.split(":", 1)[1].strip()
        elif line.lower().startswith("provider:") and line.split(":", 1)[1].strip():
            provider = line.split(":", 1)[1].strip()
        elif line.lower().startswith("provider:") and not provider:
            continue
    if not code and header:
        code = "LAB"
    row_terms = [term for term in known_terms if term.lower() in text.lower()]
    return {
        "code": code,
        "dates": ", ".join(dict.fromkeys(dates)),
        "provider": provider,
        "description": description,
        "terms": ", ".join(row_terms),
        "raw": text,
    }


def _extract_text_excerpt(text: str, *, max_chars: int = 280) -> str:
    compact_text = re.sub(r"\s+", " ", text).strip()
    if not compact_text:
        return ""
    end_positions = [compact_text.find(marker, 1) for marker in (". ", "! ", "? ")]
    end_positions = [position for position in end_positions if position != -1]
    if end_positions:
        cutoff = min(end_positions) + 1
        excerpt = compact_text[:cutoff].strip()
    else:
        excerpt = compact_text[:max_chars].strip()
    return excerpt[:max_chars].rstrip()


def _is_requisition_order(pages: list[str]) -> bool:
    haystack = "\n".join(page for page in pages if page.strip()).lower()
    return "antech requisition order" in haystack or "requisition order" in haystack


def _looks_like_cbc_or_lab_report(pages: list[str]) -> bool:
    haystack = "\n".join(page for page in pages if page.strip()).lower()
    return "cbc" in haystack or "complete blood count" in haystack or "lab results" in haystack or "hematology" in haystack


def _summarize_abnormal_lab_lines(pages: list[str]) -> str:
    abnormal_lines: list[str] = []
    for page in pages:
        for raw_line in page.splitlines():
            line = re.sub(r"\s+", " ", raw_line).strip()
            if not line:
                continue
            lowered = line.lower()
            if any(token in lowered for token in (" high", " low", " h ", " l ", "abnormal", "out of range", "elevated", "decreased", "critical", "*")):
                if len(line) > 280:
                    line = line[:277].rstrip() + "..."
                abnormal_lines.append(line)
    if not abnormal_lines:
        return ""
    unique_lines: list[str] = []
    seen: set[str] = set()
    for line in abnormal_lines:
        if line not in seen:
            unique_lines.append(line)
            seen.add(line)
    return "Abnormal findings: " + " | ".join(unique_lines[:10]) + "."


def _detect_document_family(source: PatientPdfSource, pages: list[str]) -> str:
    haystack = " ".join(
        [
            source.patient_name,
            source.pdf_url or "",
            source.pdf_path.name if source.pdf_path is not None else "",
            " ".join(page[:600] for page in pages[:2]),
        ]
    ).lower()
    if "vaccine history" in haystack or "vaccinehistory" in haystack:
        return "vaccine_history"
    if "prescriptions" in haystack or "prescription" in haystack or "rx" in haystack:
        return "prescriptions"
    if "communications" in haystack:
        return "communications"
    if "diagnoses" in haystack:
        return "diagnoses"
    if "transaction history" in haystack:
        return "transaction_history"
    if "lab test history" in haystack or "labresults" in haystack:
        return "antech_lab"
    if "medical note history" in haystack or "medical notes" in haystack:
        return "medical_notes"
    if "wellness" in haystack:
        return "wellness"
    return "other"


def _family_summary_mode(family: str) -> str:
    if family in {"antech_lab", "transaction_history"}:
        return "structured_only"
    if family in {"medical_notes", "wellness"}:
        return "clinical_summary"
    return "clinical_summary"


def _build_document_summary(
    source: PatientPdfSource,
    pages: list[str],
    detected_terms: Iterable[DetectedTerm],
    *,
    family: str,
) -> tuple[str, str]:
    mode = _family_summary_mode(family)
    if _is_requisition_order(pages):
        return "", "structured_only"
    if mode == "structured_only":
        if _looks_like_cbc_or_lab_report(pages):
            abnormal = _summarize_abnormal_lab_lines(pages)
            return abnormal, "abnormal_only" if abnormal else "structured_only"
        return "", "structured_only"
    if _looks_like_cbc_or_lab_report(pages):
        abnormal = _summarize_abnormal_lab_lines(pages)
        return abnormal, "abnormal_only" if abnormal else "structured_only"
    summary = generate_veterinary_clinical_summary(source, pages, detected_terms, family=family)
    return summary, "clinical_summary" if len(pages) <= 8 else "patient_history"


def generate_veterinary_clinical_summary(
    source: PatientPdfSource,
    pages: list[str],
    detected_terms: Iterable[DetectedTerm],
    *,
    family: str = "",
    max_preview_chars: int = 360,
) -> str:
    term_summary = summarize_detected_terms(detected_terms)
    full_text = "\n".join(page for page in pages if page.strip())
    excerpt = _extract_text_excerpt(full_text, max_chars=max_preview_chars)
    page_count = len(pages)
    table_records = _extract_table_records(pages, term_summary, family=family)
    summary_bits: list[str] = []
    if term_summary.get("medication"):
        summary_bits.append("Medications: " + ", ".join(term_summary["medication"][:12]) + ".")
    if term_summary.get("treatment"):
        summary_bits.append("Treatments: " + ", ".join(term_summary["treatment"][:12]) + ".")
    if term_summary.get("product"):
        summary_bits.append("Products: " + ", ".join(term_summary["product"][:12]) + ".")

    if page_count > 8:
        sections = [
            f"Patient history summary for {source.patient_name} ({source.patient_id}) across {page_count} pages."
        ]
        if summary_bits:
            sections.append("History signals: " + " ".join(summary_bits))
        if table_records:
            rows = []
            for record in table_records[:6]:
                row_bits = [record["code"]]
                if record["dates"]:
                    row_bits.append(record["dates"])
                if record["provider"]:
                    row_bits.append(record["provider"])
                if record["description"]:
                    row_bits.append(record["description"])
                rows.append("; ".join(row_bits))
            sections.append("Table rows: " + " | ".join(rows))
        if excerpt:
            sections.append("Historical excerpt: " + excerpt)
        return " ".join(sections)

    sections = [f"Clinical summary for {source.patient_name} ({source.patient_id}) from {page_count} page(s)."]
    if summary_bits:
        sections.append("Key signals: " + " ".join(summary_bits))
    if table_records:
        rows = []
        for record in table_records[:6]:
            row_bits = [record["code"]]
            if record["dates"]:
                row_bits.append(record["dates"])
            if record["provider"]:
                row_bits.append(record["provider"])
            if record["description"]:
                row_bits.append(record["description"])
            rows.append("; ".join(row_bits))
        sections.append("Table rows: " + " | ".join(rows))
    if excerpt:
        sections.append("Clinical excerpt: " + excerpt)
    return " ".join(sections)


def split_text(text: str, *, chunk_size: int, chunk_overlap: int) -> list[str]:
    splitter = RecursiveCharacterTextSplitter(
        chunk_size=chunk_size,
        chunk_overlap=chunk_overlap,
        separators=["\f", "\n\n", "\n", ". ", "? ", "! ", "; ", ": ", " ", ""],
    )
    return splitter.split_text(text)


def chunk_pdf_pages(
    source: PatientPdfSource,
    pages: list[str],
    config: ChunkingConfig,
    *,
    term_index: Iterable[DictionaryTerm] | None = None,
    page_workers: int | None = None,
) -> list[Document]:
    terms = list(term_index) if term_index is not None else load_term_index()
    family = _detect_document_family(source, pages)
    full_pdf_terms: list[DetectedTerm] = []
    page_terms_by_number: dict[int, list[DetectedTerm]] = {}
    profile_pdf = os.environ.get("EVH_IMPORT_PROFILE_PDF", "").strip().lower() in {"1", "true", "yes", "on"}
    profile_started = perf_counter()
    timing: dict[str, float] = {}

    worker_count = page_workers or int(os.environ.get("EVH_IMPORT_PAGE_WORKERS", "0") or 0)
    if worker_count <= 0:
        cpu_count = os.cpu_count() or 2
        worker_count = max(2, min(8, cpu_count // 2 or 2))
    worker_count = min(worker_count, max(1, len(pages)))
    verbose_insight = _verbose_pdf_insight_enabled()
    if verbose_insight:
        print(
            f"chunk_stage_start | pdf_id={source.pdf_id} | pages={len(pages)} | workers={worker_count} | chunk_size={config.chunk_size} | chunk_overlap={config.chunk_overlap} | family={family}",
            flush=True,
        )

    detect_terms_start = perf_counter()
    if worker_count <= 1:
        page_term_results = [
            (page_number, detect_terms_in_text(page_text, terms, page_number=page_number))
            for page_number, page_text in enumerate(pages, start=1)
        ]
    else:
        with ThreadPoolExecutor(max_workers=worker_count) as executor:
            page_term_results = list(
                executor.map(
                    lambda item: (item[0], detect_terms_in_text(item[1], terms, page_number=item[0])),
                    list(enumerate(pages, start=1)),
                )
            )
    for page_number, page_terms in page_term_results:
        page_terms_by_number[page_number] = page_terms
        full_pdf_terms.extend(page_terms)
    timing["detect_terms_seconds"] = perf_counter() - detect_terms_start
    if verbose_insight:
        print(
            f"chunk_stage_done | pdf_id={source.pdf_id} | stage=detect_terms | pages={len(pages)} | elapsed_s={timing['detect_terms_seconds']:.1f}",
            flush=True,
        )

    summary_start = perf_counter()
    clinical_summary, summary_style = _build_document_summary(source, pages, full_pdf_terms, family=family)
    timing["summary_seconds"] = perf_counter() - summary_start
    if verbose_insight:
        print(
            f"chunk_stage_done | pdf_id={source.pdf_id} | stage=summary | elapsed_s={timing['summary_seconds']:.1f} | summary_style={summary_style}",
            flush=True,
        )
    full_pdf_terms_metadata = detected_terms_to_metadata(full_pdf_terms)

    term_summary_start = perf_counter()
    term_summary = summarize_detected_terms(full_pdf_terms)
    timing["term_summary_seconds"] = perf_counter() - term_summary_start
    if verbose_insight:
        print(
            f"chunk_stage_done | pdf_id={source.pdf_id} | stage=term_summary | elapsed_s={timing['term_summary_seconds']:.1f} | terms={len(full_pdf_terms)}",
            flush=True,
        )

    table_records_start = perf_counter()
    table_records = _extract_table_records(pages, term_summary, family=family)
    timing["table_records_seconds"] = perf_counter() - table_records_start
    if verbose_insight:
        print(
            f"chunk_stage_done | pdf_id={source.pdf_id} | stage=table_records | elapsed_s={timing['table_records_seconds']:.1f} | records={len(table_records)}",
            flush=True,
        )

    documents: list[Document] = []
    chunk_index = 1
    split_and_chunk_start = perf_counter()
    if worker_count <= 1:
        chunk_results = [
            (page_number, split_text(page_text, chunk_size=config.chunk_size, chunk_overlap=config.chunk_overlap))
            for page_number, page_text in enumerate(pages, start=1)
        ]
    else:
        with ThreadPoolExecutor(max_workers=worker_count) as executor:
            chunk_results = list(
                executor.map(
                    lambda item: (item[0], split_text(item[1], chunk_size=config.chunk_size, chunk_overlap=config.chunk_overlap)),
                    list(enumerate(pages, start=1)),
                )
            )
    if verbose_insight:
        print(
            f"chunk_stage_done | pdf_id={source.pdf_id} | stage=split_dispatch | elapsed_s={perf_counter() - split_and_chunk_start:.1f}",
            flush=True,
        )
    for page_number, chunks in chunk_results:
        if verbose_insight:
            print(
                f"page_chunk_start | pdf_id={source.pdf_id} | page_number={page_number} | chunks={len(chunks)}",
                flush=True,
            )
        for chunk_text in chunks:
            chunk_terms = detect_terms_in_text(chunk_text, terms, page_number=page_number)
            documents.append(
                Document(
                    page_content=chunk_text,
                    metadata={
                        "patient_id": source.patient_id,
                        "patient_name": source.patient_name,
                        "pdf_id": source.pdf_id,
                        "document_pdf_id": source.pdf_id,
                        "pdf_path": str(source.pdf_path) if source.pdf_path is not None else None,
                        "pdf_url": source.pdf_url,
                        "page_number": page_number,
                        "chunk_index": chunk_index,
                        "source": "instinct-patient-pdf",
                        "document_family": family,
                        "clinical_summary": clinical_summary,
                        "clinical_summary_style": summary_style,
                        "term_summary": term_summary,
                        "detected_terms": detected_terms_to_metadata(chunk_terms),
                        "page_detected_terms": detected_terms_to_metadata(page_terms_by_number.get(page_number, [])),
                        "full_pdf_detected_terms": full_pdf_terms_metadata,
                    },
                )
            )
            chunk_index += 1
        if verbose_insight:
            print(
                f"page_chunk_done | pdf_id={source.pdf_id} | page_number={page_number} | total_chunks_so_far={len(documents)}",
                flush=True,
            )
    timing["split_and_chunk_seconds"] = perf_counter() - split_and_chunk_start
    if verbose_insight:
        print(
            f"chunk_stage_done | pdf_id={source.pdf_id} | stage=split_and_chunk | elapsed_s={timing['split_and_chunk_seconds']:.1f} | documents={len(documents)}",
            flush=True,
        )

    if profile_pdf:
        timing["total_seconds"] = perf_counter() - profile_started
        print(
            json.dumps(
                {
                    "stage": "pdf_profile",
                    "patient_id": source.patient_id,
                    "patient_name": source.patient_name,
                    "pdf_path": str(source.pdf_path) if source.pdf_path is not None else None,
                    "pdf_url": source.pdf_url,
                    "page_count": len(pages),
                    "chunk_count": len(documents),
                    **{k: round(v, 3) for k, v in timing.items()},
                },
                indent=2,
                sort_keys=True,
            ),
            flush=True,
        )
    return documents


def chunk_patient_pdf(
    source: PatientPdfSource,
    config: ChunkingConfig,
    *,
    term_index: Iterable[DictionaryTerm] | None = None,
) -> tuple[list[Document], int]:
    pages, page_count = read_pdf_text_from_source(source)
    return chunk_pdf_pages(source, pages, config, term_index=term_index), page_count


def chunk_patient_pdf_timed(
    source: PatientPdfSource,
    config: ChunkingConfig,
    *,
    term_index: Iterable[DictionaryTerm] | None = None,
    defer_no_text_page_threshold: int | None = 8,
    extraction_timeout_s: int = 45,
    page_workers: int | None = None,
    progress_state: dict[str, Any] | None = None,
) -> tuple[list[Document], int, dict[str, float]]:
    download_start = perf_counter()
    timing: dict[str, float] = {}
    print(
        json.dumps(
            {
                "status": "pdf_phase_begin",
                "phase": "read_pdf_bytes",
                "pdf_id": source.pdf_id,
                "filename": source.pdf_path.name if source.pdf_path is not None else None,
            },
            sort_keys=True,
        ),
        flush=True,
    )
    pdf_bytes = read_pdf_bytes(source)
    download_seconds = perf_counter() - download_start
    print(
        json.dumps(
            {
                "status": "pdf_phase_done",
                "phase": "read_pdf_bytes",
                "pdf_id": source.pdf_id,
                "filename": source.pdf_path.name if source.pdf_path is not None else None,
                "elapsed_seconds": round(download_seconds, 3),
                "bytes": len(pdf_bytes),
            },
            sort_keys=True,
        ),
        flush=True,
    )
    print(
        json.dumps(
            {
                "status": "pdf_gap_probe",
                "step": "after_read_before_cache_key",
                "pdf_id": source.pdf_id,
                "filename": source.pdf_path.name if source.pdf_path is not None else None,
            },
            sort_keys=True,
        ),
        flush=True,
    )
    cache_key = _cache_key_for_source(source, pdf_bytes)
    print(
        json.dumps(
            {
                "status": "pdf_gap_probe",
                "step": "cache_key_done",
                "pdf_id": source.pdf_id,
                "filename": source.pdf_path.name if source.pdf_path is not None else None,
                "cache_key_prefix": cache_key[:16],
            },
            sort_keys=True,
        ),
        flush=True,
    )
    cache_dir = DEFAULT_TEXT_CACHE_DIR
    print(
        json.dumps(
            {
                "status": "pdf_gap_probe",
                "step": "cache_dir_done",
                "pdf_id": source.pdf_id,
                "filename": source.pdf_path.name if source.pdf_path is not None else None,
                "cache_dir": str(cache_dir),
            },
            sort_keys=True,
        ),
        flush=True,
    )
    suffix = _source_suffix(source)
    print(
        json.dumps(
            {
                "status": "pdf_gap_probe",
                "step": "suffix_done",
                "pdf_id": source.pdf_id,
                "filename": source.pdf_path.name if source.pdf_path is not None else None,
                "suffix": suffix,
            },
            sort_keys=True,
        ),
        flush=True,
    )

    print(
        json.dumps(
            {
                "status": "pdf_gap_probe",
                "step": "before_cache_lookup",
                "pdf_id": source.pdf_id,
                "filename": source.pdf_path.name if source.pdf_path is not None else None,
            },
            sort_keys=True,
        ),
        flush=True,
    )
    cached = _load_cached_text_pages(cache_dir, cache_key)
    print(
        json.dumps(
            {
                "status": "pdf_gap_probe",
                "step": "after_cache_lookup",
                "pdf_id": source.pdf_id,
                "filename": source.pdf_path.name if source.pdf_path is not None else None,
                "cached": cached is not None,
            },
            sort_keys=True,
        ),
        flush=True,
    )
    if cached is not None:
        print(
            json.dumps(
                {
                    "status": "pdf_gap_probe",
                    "step": "cache_hit_branch",
                    "pdf_id": source.pdf_id,
                    "filename": source.pdf_path.name if source.pdf_path is not None else None,
                },
                sort_keys=True,
            ),
            flush=True,
        )
        pages, page_count, cached_parser = cached
        extraction_seconds = 0.0
        chunking_start = perf_counter()
        documents = chunk_pdf_pages(source, pages, config, term_index=term_index, page_workers=page_workers)
        chunking_seconds = perf_counter() - chunking_start
        summary_seconds = chunking_seconds if documents else 0.0
        print(
            json.dumps(
                {
                    "status": "pdf_phase_timing",
                    "pdf_id": source.pdf_id,
                    "filename": source.pdf_path.name if source.pdf_path is not None else None,
                    "download_seconds": round(download_seconds, 3),
                    "extraction_seconds": round(extraction_seconds, 3),
                    "chunking_seconds": round(chunking_seconds, 3),
                    "summary_seconds": round(summary_seconds, 3),
                    "cached_text_seconds": 0.0,
                    "cached_text": True,
                },
                sort_keys=True,
            ),
            flush=True,
        )
        return documents, page_count, {
            "download_seconds": download_seconds,
            "extraction_seconds": extraction_seconds,
            "chunking_seconds": chunking_seconds,
            "summary_seconds": summary_seconds,
            "cached_text_seconds": 0.0,
            "text_method": cached_parser,
        }

    print(
        json.dumps(
            {
                "status": "pdf_gap_probe",
                "step": "cache_miss_branch",
                "pdf_id": source.pdf_id,
                "filename": source.pdf_path.name if source.pdf_path is not None else None,
                "suffix": suffix,
            },
            sort_keys=True,
        ),
        flush=True,
    )
    extraction_start = perf_counter()
    print(
        json.dumps(
            {
                "status": "pdf_gap_probe",
                "step": "before_extraction_try",
                "pdf_id": source.pdf_id,
                "filename": source.pdf_path.name if source.pdf_path is not None else None,
            },
            sort_keys=True,
        ),
        flush=True,
    )
    try:
        if suffix in {".doc", ".docx"}:
            print(
                json.dumps(
                    {
                        "status": "pdf_gap_probe",
                        "step": "word_branch_selected",
                        "pdf_id": source.pdf_id,
                        "filename": source.pdf_path.name if source.pdf_path is not None else None,
                    },
                    sort_keys=True,
                ),
                flush=True,
            )
            print(
                json.dumps(
                    {
                        "status": "pdf_phase_begin",
                        "phase": "extract_word_text",
                        "pdf_id": source.pdf_id,
                        "filename": source.pdf_path.name if source.pdf_path is not None else None,
                    },
                    sort_keys=True,
                ),
                flush=True,
            )
            pages, page_count, parser_name = _extract_word_text_pages(source, pdf_bytes=pdf_bytes)
            _store_cached_text_pages(cache_dir, cache_key, pages, page_count, parser=parser_name)
            extraction_seconds = perf_counter() - extraction_start
            chunking_start = perf_counter()
            documents = chunk_pdf_pages(source, pages, config, term_index=term_index, page_workers=page_workers)
            chunking_seconds = perf_counter() - chunking_start
            summary_seconds = chunking_seconds if documents else 0.0
            print(
                json.dumps(
                    {
                        "status": "pdf_phase_timing",
                        "pdf_id": source.pdf_id,
                        "filename": source.pdf_path.name if source.pdf_path is not None else None,
                        "download_seconds": round(download_seconds, 3),
                        "extraction_seconds": round(extraction_seconds, 3),
                        "chunking_seconds": round(chunking_seconds, 3),
                        "summary_seconds": round(summary_seconds, 3),
                        "cached_text_seconds": 0.0,
                        "cached_text": False,
                        "parser": parser_name,
                    },
                    sort_keys=True,
                ),
                flush=True,
            )
            return documents, page_count, {
                "download_seconds": download_seconds,
                "extraction_seconds": extraction_seconds,
                "chunking_seconds": chunking_seconds,
                "summary_seconds": summary_seconds,
                "cached_text_seconds": 0.0,
                "text_method": parser_name,
            }
        print(
            json.dumps(
                {
                    "status": "pdf_gap_probe",
                    "step": "before_text_stage_choose",
                    "pdf_id": source.pdf_id,
                    "filename": source.pdf_path.name if source.pdf_path is not None else None,
                    "timeout_s": extraction_timeout_s,
                },
                sort_keys=True,
            ),
            flush=True,
        )
        pages, page_count, text_method = _read_pdf_text_from_path(source.pdf_path)
        timing["text_method"] = text_method
        print(
            json.dumps(
                {
                    "status": "pdf_gap_probe",
                    "step": "after_text_stage_choose",
                    "pdf_id": source.pdf_id,
                    "filename": source.pdf_path.name if source.pdf_path is not None else None,
                    "page_count": page_count,
                    "page_lengths": [len(page) for page in pages[:3]],
                    "text_method": text_method,
                },
                sort_keys=True,
            ),
            flush=True,
        )
        _store_cached_text_pages(cache_dir, cache_key, pages, page_count, parser=text_method)
        print(
            json.dumps(
                {
                    "status": "pdf_gap_probe",
                    "step": "after_store_cached_text_pages",
                    "pdf_id": source.pdf_id,
                    "filename": source.pdf_path.name if source.pdf_path is not None else None,
                    "page_count": page_count,
                },
                sort_keys=True,
            ),
            flush=True,
        )
    except (PdfReadError, RuntimeError, ValueError, OSError) as exc:
        if _looks_like_non_pdf_or_corrupt_pdf(exc):
            raise DeferredOCRDocument(
                page_count=0,
                reason=f"Deferred non-PDF or corrupt PDF ({type(exc).__name__}: {exc})",
                metadata={
                    "patient_id": source.patient_id,
                    "patient_name": source.patient_name,
                    "pdf_url": source.pdf_url,
                    "pdf_path": str(source.pdf_path) if source.pdf_path is not None else None,
                    "filename": source.pdf_path.name if source.pdf_path is not None else None,
                    "error_type": type(exc).__name__,
                    "error": str(exc),
                    "action": "defer_non_pdf_or_corrupt_pdf",
                },
            ) from exc
        raise
    except NoTextLayerError:
        page_count = 0
        try:
            page_count = PdfReader(BytesIO(pdf_bytes)).getNumPages()  # type: ignore[attr-defined]
        except Exception:
            try:
                page_count = len(PdfReader(BytesIO(pdf_bytes)).pages)
            except Exception:
                page_count = 0
        if progress_state is not None:
            progress_state["current_ocr_stage"] = "a"
        print(
            json.dumps(
                {
                    "status": "pdf_phase_begin",
                    "phase": "ocr_pdf_text_pages",
                    "pdf_id": source.pdf_id,
                    "filename": source.pdf_path.name if source.pdf_path is not None else None,
                },
                sort_keys=True,
            ),
            flush=True,
        )
        pages, page_count, ocr_method = ocr_pdf_text_pages(source.pdf_path)
        if progress_state is not None:
            progress_state["current_ocr_stage"] = "b"
        timing["ocr_used"] = True
        timing["ocr_method"] = ocr_method
    extraction_seconds = perf_counter() - extraction_start
    print(
        json.dumps(
            {
                "status": "pdf_phase_done",
                "phase": "extract_text",
                "pdf_id": source.pdf_id,
                "filename": source.pdf_path.name if source.pdf_path is not None else None,
                "elapsed_seconds": round(extraction_seconds, 3),
                "page_count": page_count,
                "parser": "ocr" if timing.get("ocr_used") else "text",
            },
            sort_keys=True,
        ),
        flush=True,
    )

    chunking_start = perf_counter()
    print(
        json.dumps(
            {
                "status": "pdf_phase_begin",
                "phase": "chunk_pdf_pages",
                "pdf_id": source.pdf_id,
                "filename": source.pdf_path.name if source.pdf_path is not None else None,
                "page_count": page_count,
            },
            sort_keys=True,
        ),
        flush=True,
    )
    documents = chunk_pdf_pages(source, pages, config, term_index=term_index, page_workers=page_workers)
    chunking_seconds = perf_counter() - chunking_start
    print(
        json.dumps(
            {
                "status": "pdf_phase_done",
                "phase": "chunk_pdf_pages",
                "pdf_id": source.pdf_id,
                "filename": source.pdf_path.name if source.pdf_path is not None else None,
                "elapsed_seconds": round(chunking_seconds, 3),
                "documents": len(documents),
            },
            sort_keys=True,
        ),
        flush=True,
    )
    print(
        json.dumps(
            {
                "status": "pdf_phase_timing",
                "pdf_id": source.pdf_id,
                "filename": source.pdf_path.name if source.pdf_path is not None else None,
                "download_seconds": round(download_seconds, 3),
                "extraction_seconds": round(extraction_seconds, 3),
                "chunking_seconds": round(chunking_seconds, 3),
                "summary_seconds": round(chunking_seconds if documents else 0.0, 3),
                "cached_text_seconds": 0.0,
                "cached_text": False,
                "ocr_used": bool(progress_state and progress_state.get("current_ocr_stage")),
            },
            sort_keys=True,
        ),
        flush=True,
    )

    if not documents and _detect_document_family(source, pages) == "transaction_history":
        ocr_start = perf_counter()
        if progress_state is not None:
            progress_state["current_ocr_stage"] = "c"
        ocr_pages, ocr_page_count, ocr_method = ocr_pdf_text_pages(source.pdf_path)
        timing["ocr_retry_seconds"] = perf_counter() - ocr_start
        timing["ocr_used"] = True
        timing["ocr_method"] = ocr_method
        pages = ocr_pages
        page_count = ocr_page_count
        chunking_start = perf_counter()
        documents = chunk_pdf_pages(source, pages, config, term_index=term_index, page_workers=page_workers)
        chunking_seconds = perf_counter() - chunking_start
        timing["ocr_retry_chunking_seconds"] = chunking_seconds

    summary_seconds = 0.0
    if documents:
        # Summary generation is already embedded in chunk_pdf_pages; estimate via
        # the chunking wall clock for now and expose a dedicated bucket for future
        # stage splits.
        summary_seconds = chunking_seconds

    if "text_method" not in timing:
        timing["text_method"] = "unknown"

    return documents, page_count, {
        "download_seconds": download_seconds,
        "extraction_seconds": extraction_seconds,
        "chunking_seconds": chunking_seconds,
        "summary_seconds": summary_seconds,
        "cached_text_seconds": 0.0,
        **{k: v for k, v in timing.items() if k in {"text_method", "ocr_method", "ocr_used"}},
    }


def chunk_patient_manifest(
    manifest: Iterable[PatientPdfSource],
    config: ChunkingConfig,
    *,
    term_index: Iterable[DictionaryTerm] | None = None,
) -> tuple[list[Document], int]:
    documents: list[Document] = []
    page_count = 0
    terms = list(term_index) if term_index is not None else load_term_index()
    for source in manifest:
        source_documents, source_pages = chunk_patient_pdf(source, config, term_index=terms)
        documents.extend(source_documents)
        page_count += source_pages
    return documents, page_count


