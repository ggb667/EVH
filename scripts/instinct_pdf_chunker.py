def load_patient_manifest(path: Path) -> list[PatientPdfSource]:
    raw = path.read_text(encoding="utf-8")
    payload = json.loads(raw)
    if not isinstance(payload, list):
        raise ValueError("patient manifest must be a JSON array")

    entries: list[PatientPdfSource] = []
    for item in payload:
        if not isinstance(item, dict):
            raise ValueError("patient manifest entries must be JSON objects")

        patient_id = str(item.get("patient_id") or item.get("id") or "").strip()
        patient_name = str(item.get("patient_name") or item.get("name") or "").strip()
        pdf_value = item.get("pdf_path") or item.get("pdf")
        pdf_url = item.get("pdf_url") or item.get("source_url") or item.get("attachment_url")

        if not patient_id:
            raise ValueError(f"manifest entry is missing patient_id: {item!r}")
        if not patient_name:
            raise ValueError(f"manifest entry is missing patient_name: {item!r}")

        pdf_path = Path(pdf_value) if isinstance(pdf_value, str) and pdf_value.strip() else None
        if pdf_path is None and not (isinstance(pdf_url, str) and pdf_url.strip()):
            raise ValueError(f"manifest entry is missing pdf_path or pdf_url: {item!r}")

        entries.append(
            PatientPdfSource(
                patient_id=patient_id,
                patient_name=patient_name,
                pdf_path=pdf_path,
                pdf_url=pdf_url if isinstance(pdf_url, str) and pdf_url.strip() else None,
            )
        )

    return entries


def read_pdf_bytes(source: PatientPdfSource) -> bytes:
    if source.pdf_url:
        from scripts.http_session import get_session

        response = get_session().get(source.pdf_url, timeout=120)
        response.raise_for_status()
        return response.content
    if source.pdf_path is None:
        raise ValueError("patient PDF source must include pdf_path or pdf_url")
    return source.pdf_path.read_bytes()


def _source_suffix(source: PatientPdfSource) -> str:
    if source.pdf_path is not None:
        return source.pdf_path.suffix.lower()
    if source.pdf_url:
        return Path(urlparse(source.pdf_url).path).suffix.lower()
    return ""


def _detect_word_parser() -> tuple[str | None, str | None]:
    for name in ("antiword", "catdoc", "libreoffice", "soffice"):
        path = shutil.which(name)
        if path:
            if name == "soffice":
                name = "libreoffice"
            return name, path
    return None, None


def _cache_key_for_source(source: PatientPdfSource, payload: bytes | None = None) -> str:
    hasher = hashlib.sha256()
    hasher.update((source.pdf_path.name if source.pdf_path is not None else source.pdf_url or "").encode("utf-8"))
    if payload is not None:
        hasher.update(payload)
    return hasher.hexdigest()


def _load_cached_text_pages(cache_dir: Path, cache_key: str) -> tuple[list[str], int, str] | None:
    cache_file = cache_dir / f"{cache_key}.json"
    if not cache_file.exists():
        return None
    try:
        payload = json.loads(cache_file.read_text(encoding="utf-8"))
        pages = payload.get("pages")
        page_count = int(payload.get("page_count") or 0)
        parser = str(payload.get("parser") or "unknown")
        if isinstance(pages, list):
            return [str(page) for page in pages], page_count or len(pages), parser
    except Exception:
        return None
    return None


def _store_cached_text_pages(cache_dir: Path, cache_key: str, pages: list[str], page_count: int, *, parser: str) -> None:
    cache_dir.mkdir(parents=True, exist_ok=True)
    cache_file = cache_dir / f"{cache_key}.json"
    cache_file.write_text(
        json.dumps(
            {
                "parser": parser,
                "page_count": page_count,
                "pages": pages,
            },
            ensure_ascii=False,
        ),
        encoding="utf-8",
    )


