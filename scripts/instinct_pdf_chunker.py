def embed_texts_openai(
    texts: list[str],
    *,
    model: str = DEFAULT_EMBEDDING_MODEL,
    dimensions: int | None = DEFAULT_EMBEDDING_DIMENSIONS,
) -> list[list[float]]:
    if not texts:
        return []
    payload: dict[str, Any] = {
        "model": model,
        "input": texts,
    }
    if dimensions is not None:
        payload["dimensions"] = dimensions
    request = urllib_request.Request(
        "https://api.openai.com/v1/embeddings",
        data=json.dumps(payload).encode("utf-8"),
        headers={
            "Authorization": f"Bearer {_openai_api_key()}",
            "Content-Type": "application/json",
        },
        method="POST",
    )
    with urllib_request.urlopen(request, timeout=240) as response:
        data = json.loads(response.read().decode("utf-8"))
    items = data.get("data") or []
    vectors: list[list[float]] = []
    for item in items:
        vector = item.get("embedding")
        if not isinstance(vector, list):
            raise RuntimeError("OpenAI embeddings response did not include embedding vectors.")
        vectors.append([float(value) for value in vector])
    if len(vectors) != len(texts):
        raise RuntimeError("OpenAI embeddings response size did not match requested batch size.")
    return vectors


def embed_texts_openai_with_retry(
    texts: list[str],
    *,
    model: str = DEFAULT_EMBEDDING_MODEL,
    dimensions: int | None = DEFAULT_EMBEDDING_DIMENSIONS,
    max_attempts: int = 3,
    base_delay_s: float = 2.0,
) -> list[list[float]]:
    if not texts:
        return []
    last_error: Exception | None = None
    for attempt in range(1, max_attempts + 1):
        try:
            return embed_texts_openai(texts, model=model, dimensions=dimensions)
        except Exception as exc:
            last_error = exc
            if attempt >= max_attempts:
                break
            sleep_s = base_delay_s * (2 ** (attempt - 1))
            print(
                f"embedding_retry | attempt={attempt} | max_attempts={max_attempts} | batch_size={len(texts)} | error_type={type(exc).__name__} | error={exc} | sleep_s={sleep_s}",
                flush=True,
            )
            time.sleep(sleep_s)
    raise RuntimeError(
        f"OpenAI embedding request failed after {max_attempts} attempts for batch_size={len(texts)}: {last_error}"
    ) from last_error


def vector_literal(values: Iterable[float]) -> str:
    return "[" + ",".join(f"{value:.6f}" for value in values) + "]"


def sql_quote(value: str | None) -> str:
    if value is None:
        return "NULL"
    text = str(value)
    tag = "q"
    while f"${tag}$" in text:
        tag += "q"
    return f"${tag}${text}${tag}$"


def _strip_nuls(value: Any) -> Any:
    if isinstance(value, str):
        return value.replace("\x00", "")
    if isinstance(value, list):
        return [_strip_nuls(item) for item in value]
    if isinstance(value, tuple):
        return tuple(_strip_nuls(item) for item in value)
    if isinstance(value, Mapping):
        cleaned: dict[Any, Any] = {}
        for key, item in value.items():
            try:
                cleaned[key] = _strip_nuls(item)
            except Exception:
                cleaned[key] = str(item).replace("\x00", "")
        return cleaned
    if isinstance(value, Sequence) and not isinstance(value, (bytes, bytearray)):
        return [_strip_nuls(item) for item in value]
    return value


