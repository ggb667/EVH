def run_psql(database_url: str, sql: str) -> subprocess.CompletedProcess[str]:
    from urllib.parse import unquote, urlparse

    env = os.environ.copy()
    sql_text = sql.strip()
    sql_preview = " ".join(sql_text.split())[:220]

    def _clean(value: str | None) -> str | None:
        if value is None:
            return None
        text = " ".join(str(value).split()).strip()
        return text or None

    def _apply_env_from_shell() -> bool:
        host = _clean(env.get("EVH_PGHOST") or env.get("PGHOST"))
        port = _clean(env.get("EVH_PGPORT") or env.get("PGPORT"))
        user = _clean(env.get("EVH_PGUSER") or env.get("PGUSER"))
        password = _clean(env.get("EVH_PGPASSWORD") or env.get("PGPASSWORD"))
        database = _clean(env.get("EVH_PGDATABASE") or env.get("PGDATABASE"))
        if host:
            env["PGHOST"] = host
        if port:
            env["PGPORT"] = str(port)
        if user:
            env["PGUSER"] = user
        if password:
            env["PGPASSWORD"] = password
        if database:
            env["PGDATABASE"] = database
        if host and "rds.amazonaws.com" in host and not env.get("PGSSLMODE"):
            env["PGSSLMODE"] = "require"
        return bool(host and user and database)

    def _apply_env_from_url(url: str) -> bool:
        normalized = " ".join(url.split())
        try:
            parsed = urlparse(normalized)
        except Exception:
            return False
        if not parsed.scheme.startswith("postgres"):
            return False
        if parsed.hostname:
            env["PGHOST"] = _clean(parsed.hostname) or parsed.hostname
        try:
            port = parsed.port
        except ValueError:
            port = None
        if port:
            env["PGPORT"] = str(port)
        if parsed.username:
            env["PGUSER"] = _clean(unquote(parsed.username)) or unquote(parsed.username)
        if parsed.password:
            env["PGPASSWORD"] = _clean(unquote(parsed.password)) or unquote(parsed.password)
        if parsed.path and parsed.path != "/":
            env["PGDATABASE"] = _clean(parsed.path.lstrip("/")) or parsed.path.lstrip("/")
        if env.get("PGHOST") and "rds.amazonaws.com" in env["PGHOST"] and not env.get("PGSSLMODE"):
            env["PGSSLMODE"] = "require"
        return bool(env.get("PGHOST") and env.get("PGUSER") and env.get("PGDATABASE"))

    def _dsn_from_env() -> str | None:
        host = env.get("PGHOST")
        port = env.get("PGPORT")
        user = env.get("PGUSER")
        password = env.get("PGPASSWORD")
        database = env.get("PGDATABASE")
        if not (host and user and database):
            return None
        parts = [f"host={host}", f"dbname={database}", f"user={user}"]
        if port:
            parts.append(f"port={port}")
        if password:
            parts.append(f"password={password}")
        if env.get("PGSSLMODE"):
            parts.append(f"sslmode={env['PGSSLMODE']}")
        return " ".join(parts)

    def _run_psql_with_args(extra_args: list[str]) -> subprocess.CompletedProcess[str]:
        with tempfile.NamedTemporaryFile("w", suffix=".sql", delete=False, encoding="utf-8") as temp_sql:
            temp_sql.write(sql_text)
            temp_sql_path = temp_sql.name
        try:
            print(
                json.dumps(
                    {
                        "stage": "psql_start",
                        "sql_bytes": len(sql_text.encode("utf-8")),
                        "sql_preview": sql_preview,
                        "extra_args": extra_args,
                        "pg_host": env.get("PGHOST"),
                        "pg_port": env.get("PGPORT"),
                        "pg_user": env.get("PGUSER"),
                        "pg_database": env.get("PGDATABASE"),
                        "pg_sslmode": env.get("PGSSLMODE"),
                    },
                    indent=2,
                    sort_keys=True,
                ),
                flush=True,
            )
            start = time.perf_counter()
            completed = subprocess.run(
                ["psql", "-v", "ON_ERROR_STOP=1", "-q", "-X", "-A", "-t", *extra_args, "-f", temp_sql_path],
                check=True,
                text=True,
                capture_output=True,
                env=env,
                timeout=180,
            )
            elapsed = time.perf_counter() - start
            print(
                json.dumps(
                    {
                        "stage": "psql_done",
                        "elapsed_seconds": round(elapsed, 3),
                        "stdout_bytes": len(completed.stdout or ""),
                        "stderr_bytes": len(completed.stderr or ""),
                        "sql_preview": sql_preview,
                    },
                    indent=2,
                    sort_keys=True,
                ),
                flush=True,
            )
            return completed
        except subprocess.TimeoutExpired as exc:
            print(
                json.dumps(
                    {
                        "stage": "psql_timeout",
                        "timeout_seconds": 180,
                        "sql_preview": sql_preview,
                        "extra_args": extra_args,
                        "error": str(exc),
                    },
                    indent=2,
                    sort_keys=True,
                ),
                file=sys.stderr,
                flush=True,
            )
            raise
        except subprocess.CalledProcessError as exc:
            print(
                json.dumps(
                    {
                        "stage": "psql_failed",
                        "returncode": exc.returncode,
                        "sql_preview": sql_preview,
                        "stdout": (exc.stdout or "")[:2000],
                        "stderr": (exc.stderr or "")[:2000],
                    },
                    indent=2,
                    sort_keys=True,
                ),
                file=sys.stderr,
                flush=True,
            )
            raise
        finally:
            try:
                os.unlink(temp_sql_path)
            except FileNotFoundError:
                pass

    if _apply_env_from_shell():
        try:
            print(json.dumps({"stage": "psql_env_source", "mode": "shell"}, indent=2, sort_keys=True), flush=True)
            return _run_psql_with_args([])
        except subprocess.CalledProcessError:
            raise

    if _apply_env_from_url(database_url):
        try:
            print(json.dumps({"stage": "psql_env_source", "mode": "url"}, indent=2, sort_keys=True), flush=True)
            return _run_psql_with_args([])
        except subprocess.CalledProcessError:
            raise

    dsn = _dsn_from_env()
    if dsn:
        try:
            print(json.dumps({"stage": "psql_env_source", "mode": "dsn"}, indent=2, sort_keys=True), flush=True)
            return _run_psql_with_args([dsn])
        except subprocess.CalledProcessError:
            raise

    sanitized_url = _clean(database_url) or database_url
    try:
        print(json.dumps({"stage": "psql_env_source", "mode": "sanitized_url"}, indent=2, sort_keys=True), flush=True)
        return _run_psql_with_args([sanitized_url])
    except subprocess.CalledProcessError as exc:
        print(
            json.dumps(
                {
                    "stage": "psql_failed",
                    "returncode": exc.returncode,
                    "sql_preview": sql_preview,
                    "stdout": (exc.stdout or "")[:2000],
                    "stderr": (exc.stderr or "")[:2000],
                },
                indent=2,
                sort_keys=True,
            ),
            file=sys.stderr,
            flush=True,
        )
        raise


