def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Chunk a PDF and load enhanced chunks into Postgres/pgvector.")
    parser.add_argument("--database-url", required=True, help="Postgres connection URL for the vector DB.")
    parser.add_argument("--source-name", required=True, help="Human-readable source name for the PDF.")
    parser.add_argument("--pdf-path", help="Local PDF path.")
    parser.add_argument("--pdf-url", help="Remote PDF URL.")
    parser.add_argument("--source-uri", help="Canonical source URI to store with the chunk metadata.")
    parser.add_argument("--dictionary-csv", help="CSV dictionary seed with term_type, canonical_name, and aliases columns.")
    parser.add_argument("--table-name", default=DEFAULT_TABLE_NAME)
    parser.add_argument("--embedding-model", default=DEFAULT_EMBEDDING_MODEL)
    parser.add_argument("--vector-dimensions", type=int, default=DEFAULT_EMBEDDING_DIMENSIONS)
    parser.add_argument("--chunk-size", type=int, default=1000)
    parser.add_argument("--chunk-overlap", type=int, default=150)
    parser.add_argument(
        "--print-metadata",
        action="store_true",
        help="Print chunk metadata and text previews to the console before loading.",
    )
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)

    source = PatientPdfSource(
        patient_id="benchmark",
        patient_name=args.source_name,
        pdf_path=Path(args.pdf_path) if args.pdf_path else None,
        pdf_url=args.pdf_url,
    )

    extraction_start = perf_counter()
    try:
        pages, page_count = read_pdf_text_from_source(source)
    except NoTextLayerError as exc:
        print(_skip_result_json(args.source_name, exc))
        return 0
    extraction_seconds = perf_counter() - extraction_start

    dictionary_path = Path(args.dictionary_csv) if args.dictionary_csv else None
    term_index = load_term_index(dictionary_path)
    config = ChunkingConfig(chunk_size=args.chunk_size, chunk_overlap=args.chunk_overlap)

    chunking_start = perf_counter()
    documents = chunk_pdf_pages(source, pages, config, term_index=term_index)
    chunking_seconds = perf_counter() - chunking_start
    clinical_summary = documents[0].metadata.get("clinical_summary", "") if documents else generate_veterinary_clinical_summary(source, pages, [])

    if args.print_metadata:
        print_chunk_metadata(documents)

    if args.dry_run:
        print(
            json.dumps(
                {
                    "source_name": args.source_name,
                    "status": "ready",
                    "status_code": 200,
                    "page_count": page_count,
                    "chunk_count": len(documents),
                    "clinical_summary": clinical_summary,
                    "term_summary": documents[0].metadata.get("term_summary", {}) if documents else {},
                    "extraction_seconds": extraction_seconds,
                    "chunking_seconds": chunking_seconds,
                    "vector_dimensions": args.vector_dimensions,
                },
                indent=2,
                sort_keys=True,
            )
        )
        return 0

