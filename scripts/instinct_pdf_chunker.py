class NoTextLayerError(RuntimeError):
    """Raised when a PDF has pages but no extractable text layer."""

    status_code = SKIPPED_NO_TEXT_STATUS_CODE

    def __init__(self, page_count: int) -> None:
        self.page_count = page_count
        super().__init__(f"{NO_TEXT_LAYER_ERROR} pages={page_count}")


class DeferredOCRDocument(RuntimeError):
    """Raised when a no-text-layer PDF should be deferred for later OCR."""

    def __init__(self, *, page_count: int, reason: str, metadata: dict[str, Any] | None = None) -> None:
        self.page_count = page_count
        self.reason = reason
        self.metadata = metadata or {}
        super().__init__(reason)


def _looks_like_non_pdf_or_corrupt_pdf(exc: Exception) -> bool:
    message = f"{type(exc).__name__}: {exc}".lower()
    return any(
        needle in message
        for needle in (
            "invalid pdf",
            "ole header",
            "pdfstreamerror",
            "pdf read error",
            "eof marker",
            "malformed",
            "not a valid pdf",
            "cannot read an empty file",
        )
    )


