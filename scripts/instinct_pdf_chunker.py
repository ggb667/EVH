def load_into_postgres(
    *,
    database_url: str,
    table_name: str,
    source_document_table_name: str = DEFAULT_SOURCE_DOCUMENT_TABLE_NAME,
    source_name: str,
    source_uri: str | None,
    documents: list[Document],
    vector_dimensions: int,
    embedding_model: str = DEFAULT_EMBEDDING_MODEL,
) -> tuple[float, float]:
    rows: list[dict[str, Any]] = []
    embed_start = perf_counter()
    source_summary: str = ""
    source_summary_kind: str = "structured_only"
    source_page_count = 0
    embeddings = embed_texts_openai(
        [document.page_content for document in documents],
        model=embedding_model,
        dimensions=vector_dimensions,
    )
    for document, embedding in zip(documents, embeddings):
        clean_chunk_text = _strip_nuls(document.page_content)
        clean_metadata = _strip_nuls(
            {
                **document.metadata,
                "source_name": source_name,
                "source_uri": source_uri,
            }
        )
        chunk_hash = hashlib.sha256(
            f"{source_name}:{document.metadata['chunk_index']}:{clean_chunk_text}".encode("utf-8")
        ).hexdigest()
        rows.append(
            {
                "source_name": source_name,
                "source_uri": source_uri,
                "page_number": document.metadata["page_number"],
                "chunk_index": document.metadata["chunk_index"],
                "chunk_text": clean_chunk_text,
                "chunk_hash": chunk_hash,
                "embedding": vector_literal(embedding),
                "metadata": clean_metadata,
            }
        )
        source_summary = _strip_nuls(document.metadata.get("clinical_summary", "") or source_summary)
        source_summary_kind = document.metadata.get("clinical_summary_style", "") or source_summary_kind
        source_page_count = max(source_page_count, int(document.metadata.get("page_number") or 0))
    embedding_seconds = perf_counter() - embed_start

    load_start = perf_counter()
    conn = psycopg.connect(database_url)
    try:
        conn.execute("SET SESSION statement_timeout = 0")
        if documents:
            source_document = documents[0]
            clean_source_name = _strip_nuls(source_name)
            clean_source_uri = _strip_nuls(source_uri)
            clean_summary = _strip_nuls(source_summary)
            clean_source_metadata = _strip_nuls(
                {
                    "patient_id": source_document.metadata.get("patient_id"),
                    "patient_name": source_document.metadata.get("patient_name"),
                    "summary_style": source_summary_kind,
                    "term_summary": source_document.metadata.get("term_summary"),
                    "full_pdf_detected_terms": source_document.metadata.get("full_pdf_detected_terms"),
                }
            )
            conn.execute(
                f"""
                INSERT INTO {source_document_table_name} (
                    source_name,
                    source_uri,
                    content_hash,
                    content_length,
                    page_count,
                    chunk_count,
                    summary,
                    status,
                    metadata
                )
                VALUES (%s, %s, %s, %s, %s, %s, %s, 'complete', %s)
                ON CONFLICT (content_hash) DO UPDATE SET
                    source_name = EXCLUDED.source_name,
                    source_uri = EXCLUDED.source_uri,
                    content_length = EXCLUDED.content_length,
                    page_count = EXCLUDED.page_count,
                    chunk_count = EXCLUDED.chunk_count,
                    summary = EXCLUDED.summary,
                    status = EXCLUDED.status,
                    processed_at = now(),
                    metadata = EXCLUDED.metadata
                """,
                (
                    clean_source_name,
                    clean_source_uri,
                    hashlib.sha256((source_uri or source_name).encode("utf-8")).hexdigest(),
                    sum(len(page.page_content) for page in documents),
                    source_page_count,
                    len(documents),
                    clean_summary,
                    json.dumps(
                        clean_source_metadata,
                        sort_keys=True,
                    ),
                ),
            )
        if rows:
            chunk_rows = [
                (
                    _strip_nuls(row["source_name"]),
                    _strip_nuls(row.get("source_uri")),
                    int(row["page_number"]),
                    int(row["chunk_index"]),
                    _strip_nuls(row["chunk_text"]),
                    row["chunk_hash"],
                    row["embedding"],
                    json.dumps(_strip_nuls(row["metadata"]), sort_keys=True),
                )
                for row in rows
            ]
            with conn.cursor() as cur:
                cur.executemany(
                    f"""
                    INSERT INTO {table_name} (
                        source_name,
                        source_uri,
                        page_number,
                        chunk_index,
                        chunk_text,
                        chunk_hash,
                        embedding,
                        metadata
                    )
                    VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
                    ON CONFLICT (chunk_hash) DO UPDATE SET
                        source_uri = EXCLUDED.source_uri,
                        page_number = EXCLUDED.page_number,
                        chunk_index = EXCLUDED.chunk_index,
                        chunk_text = EXCLUDED.chunk_text,
                        embedding = EXCLUDED.embedding,
                        metadata = EXCLUDED.metadata
                    """,
                    chunk_rows,
                )
        conn.commit()
    finally:
        conn.close()
    load_seconds = perf_counter() - load_start
    return embedding_seconds, load_seconds


