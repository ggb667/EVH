def ensure_vector_schema(
    *,
    database_url: str,
    table_name: str,
    source_document_table_name: str,
    vector_dimensions: int,
) -> None:
    print(json.dumps({"stage": "schema_step", "action": "schema_state_bootstrap_start"}, indent=2, sort_keys=True), flush=True)
    run_psql(database_url, build_schema_state_sql())
    print(json.dumps({"stage": "schema_step", "action": "schema_version_read_start", "table_name": table_name}, indent=2, sort_keys=True), flush=True)
    schema_version_result = run_psql(database_url, build_schema_version_read_sql(table_name))
    current_schema_version = None
    if schema_version_result.stdout.strip():
        try:
            current_schema_version = int(schema_version_result.stdout.strip().splitlines()[-1].strip())
        except ValueError:
            current_schema_version = None

    if current_schema_version != DEFAULT_SCHEMA_VERSION:
        print(
            json.dumps(
                {
                    "stage": "schema_step",
                    "action": "schema_rebuild_required",
                    "current_schema_version": current_schema_version,
                    "expected_schema_version": DEFAULT_SCHEMA_VERSION,
                    "table_name": table_name,
                },
                indent=2,
                sort_keys=True,
            ),
            flush=True,
        )
        schema_sql = build_schema_sql(table_name, vector_dimensions)
        source_document_schema_sql = build_source_document_schema_sql(source_document_table_name)
        print(json.dumps({"stage": "schema_step", "action": "schema_rebuild_start", "table_name": table_name, "source_document_table_name": source_document_table_name}, indent=2, sort_keys=True), flush=True)
        run_psql(database_url, schema_sql + "\n\n" + source_document_schema_sql)
        print(json.dumps({"stage": "schema_step", "action": "schema_version_write_start", "table_name": table_name, "schema_version": DEFAULT_SCHEMA_VERSION}, indent=2, sort_keys=True), flush=True)
        run_psql(database_url, build_schema_version_write_sql(table_name, DEFAULT_SCHEMA_VERSION))
    else:
        print(json.dumps({"stage": "schema_step", "action": "source_document_schema_start", "table_name": source_document_table_name}, indent=2, sort_keys=True), flush=True)
        run_psql(database_url, build_source_document_schema_sql(source_document_table_name))
    print(json.dumps({"stage": "schema_step", "action": "schema_bootstrap_done", "table_name": table_name}, indent=2, sort_keys=True), flush=True)


