def build_upsert_sql(table_name: str, rows: list[dict[str, Any]]) -> str:
    if not rows:
        return ""

    values_sql = []
    for row in rows:
        values_sql.append(
            "("
            + ", ".join(
                [
                    sql_quote(str(row["source_name"])),
                    sql_quote(row.get("source_uri")),
                    str(int(row["page_number"])),
                    str(int(row["chunk_index"])),
                    sql_quote(str(row["chunk_text"])),
                    sql_quote(str(row["chunk_hash"])),
                    sql_quote(str(row["embedding"])),
                    sql_quote(json.dumps(row["metadata"], sort_keys=True)),
                ]
            )
            + ")"
        )

    return f"""
INSERT INTO {table_name} (
    source_name,
    source_uri,
    page_number,
    chunk_index,
    chunk_text,
    chunk_hash,
    embedding,
    metadata
)
VALUES {", ".join(values_sql)}
ON CONFLICT (chunk_hash) DO UPDATE SET
    source_uri = EXCLUDED.source_uri,
    page_number = EXCLUDED.page_number,
    chunk_index = EXCLUDED.chunk_index,
    chunk_text = EXCLUDED.chunk_text,
    embedding = EXCLUDED.embedding,
    metadata = EXCLUDED.metadata;
""".strip()


