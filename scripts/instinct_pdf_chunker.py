def _split_aliases(raw_aliases: str | None) -> tuple[str, ...]:
    if raw_aliases is None:
        return ()
    raw_aliases = raw_aliases.strip()
    if not raw_aliases:
        return ()
    if raw_aliases.startswith("["):
        try:
            payload = json.loads(raw_aliases)
        except json.JSONDecodeError:
            payload = None
        if isinstance(payload, list):
            return tuple(str(item).strip() for item in payload if str(item).strip())
    return tuple(alias.strip() for alias in raw_aliases.split(",") if alias.strip())


def _parse_bool(value: str | None) -> bool:
    return str(value or "").strip().lower() not in {"0", "false", "no", "inactive"}


def _aws_data_api_query(sql: str) -> list[dict[str, Any]]:
    cluster_arn = os.environ.get("DB_CLUSTER_ARN")
    secret_arn = os.environ.get("DB_SECRET_ARN")
    database = os.environ.get("DB_NAME")
    if not cluster_arn or not secret_arn or not database:
        raise RuntimeError("DB_CLUSTER_ARN, DB_SECRET_ARN, and DB_NAME must be set.")

    last_error = ""
    for attempt in range(5):
        proc = subprocess.run(
            [
                "aws",
                "rds-data",
                "execute-statement",
                "--resource-arn",
                cluster_arn,
                "--secret-arn",
                secret_arn,
                "--database",
                database,
                "--sql",
                sql,
                "--include-result-metadata",
                "--format-records-as",
                "JSON",
            ],
            capture_output=True,
            text=True,
        )
        if proc.returncode == 0:
            payload = json.loads(proc.stdout or "{}")
            return json.loads(payload.get("formattedRecords", "[]"))

        last_error = (proc.stderr or proc.stdout or "").strip()
        if "DatabaseResumingException" in last_error and attempt < 4:
            time.sleep(2 * (attempt + 1))
            continue
        break
    raise RuntimeError(last_error or "AWS Data API query failed")


