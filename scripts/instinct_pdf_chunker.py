"""Chunk Instinct patient PDFs and load enhanced chunks into pgvector.

The loader keeps the PDF pipeline inspectable:
- read a PDF from disk or URL
- extract page text, skipping image-only PDFs with a 204-style result
- detect medication, treatment, and product terms
- generate one clinical summary for the full PDF
- split page text into overlapping chunks
- attach summary and detected terms to each chunk's metadata
- load enhanced chunk rows into a Postgres/pgvector table

Embeddings are generated by a real provider so the stored vectors are ready for
production RAG workflows rather than benchmark-only placeholder math.
"""

