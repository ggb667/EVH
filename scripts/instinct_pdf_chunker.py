def print_chunk_metadata(documents: list[Document]) -> None:
    seen_keys: set[str] = set()
    for document in documents:
        metadata = document.metadata
        metadata_keywords = sorted(key for key, value in metadata.items() if value is not None and value != "")
        seen_keys.update(metadata_keywords)
        summary = {
            "chunk_index": metadata.get("chunk_index"),
            "page_number": metadata.get("page_number"),
            "patient_id": metadata.get("patient_id"),
            "patient_name": metadata.get("patient_name"),
            "source": metadata.get("source"),
            "metadata_keywords": metadata_keywords,
            "term_summary": metadata.get("term_summary"),
            "detected_terms": metadata.get("detected_terms"),
            "clinical_summary": metadata.get("clinical_summary"),
            "pdf_path": metadata.get("pdf_path"),
            "pdf_url": metadata.get("pdf_url"),
            "chunk_chars": len(document.page_content),
            "preview": document.page_content[:160],
        }
        print(pformat(summary, sort_dicts=False))
    print(pformat({"unique_metadata_keywords": sorted(seen_keys)}, sort_dicts=False))


